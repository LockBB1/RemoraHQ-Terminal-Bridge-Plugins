# frozen_string_literal: true
# One bounded, non-interactive job. Secrets arrive only through stdin.
ENV['BUNDLE_GEMFILE'] ||= '/opt/remorahq-winrm/Gemfile'
ENV['BUNDLE_PATH'] ||= '/opt/remorahq-winrm/vendor/bundle'
require 'bundler/setup'
require 'json'
require 'logger'
require 'open3'
require 'fileutils'
require 'winrm'
require 'winrm-fs'
require 'winrm/shells/base'
require 'gssapi'
require 'gssapi/extensions'
raise 'unsupported_winrm_version' unless Gem.loaded_specs.fetch('winrm').version.to_s == '2.4.1'
require_relative 'gssapi-safety'

begin
  job = JSON.parse(STDIN.read(2 * 1024 * 1024))
  username = job.fetch('username')
  raise 'invalid principal' unless username.match?(/\A[A-Za-z0-9._-]+@[A-Za-z0-9.-]+\z/)
  raise 'invalid host' unless job.fetch('host').match?(/\A(?=.{1,253}\z)[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?\z/) && job['host'].include?('.') && !job['host'].match?(/\A[\d.]+\z/)
  directory = job.fetch('cacheDirectory')
  begin
    cache = "FILE:#{directory}/ccache"
    ENV['KRB5CCNAME'] = cache
    # HTTP proxies and debug traces must never receive WinRM traffic or SOAP.
    %w[HTTP_PROXY HTTPS_PROXY ALL_PROXY http_proxy https_proxy all_proxy].each { |name| ENV.delete(name) }
    password = job.delete('password')
    _, _, status = Open3.capture3({ 'KRB5CCNAME' => cache }, '/usr/bin/kinit', '-l', '10m', '-F', '-P', username, stdin_data: password + "\n")
    password.replace("\0" * password.bytesize)
    raise 'kerberos failed' unless status.success?
    connection = WinRM::Connection.new(endpoint: "http://#{job['host']}:5985/wsman", transport: :kerberos,
      user: username, realm: username.split('@').last, service: 'HTTP',
      logger: Logger.new(File::NULL, level: Logger::FATAL), retry_limit: 1, operation_timeout: 60)
    connection.shell(:powershell) do |shell|
      if job['mode'] == 'probe'
        result = shell.run("$ErrorActionPreference='Stop'; if (-not ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) { throw 'admin_required' }; 'winrm-ok'")
        raise 'probe failed' unless result.exitcode == 0 && result.stdout.lines.any? { |line| line.strip == 'winrm-ok' }
        puts 'ping=Unknown;winrm=True'
      elsif job['mode'] == 'diagnostic'
        id = job.fetch('operationId')
        raise 'invalid job' unless id.match?(/\A[a-f0-9]{32}\z/) && job.fetch('installerSha256').match?(/\A[a-f0-9]{64}\z/)
        directory_script = [job.fetch('directoryScript')].pack('m0')
        directory_command = ->(action) { "$s=[Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('#{directory_script}')); & ([scriptblock]::Create($s)) -Action '#{action}' -OperationId '#{id}'" }
        diagnostic_marker = 'ri-diagnostic:error:error:unknown'
        cleanup = 'unknown'
        directory_created = false
        begin
          created = shell.run(directory_command.call('create'))
          path = created.stdout.lines.map(&:strip).grep(/\Ari-directory:/).last.to_s.delete_prefix('ri-directory:')
          raise 'directory unavailable' unless created.exitcode == 0 && path.match?(/\A[A-Za-z]:\\[^\r\n']+\\RemoraHQ-Diagnostic-#{id}\\installer\.exe\z/)
          directory_created = true
          WinRM::FS::FileManager.new(connection).upload(job.fetch('localExe'), path)
          encoded = [job.fetch('script')].pack('m0')
          cmd = "$s=[Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('#{encoded}')); & ([scriptblock]::Create($s)) -Installer '#{path}' -InstallerSha256 '#{job.fetch('installerSha256')}'"
          checked = shell.run(cmd)
          marker = checked.stdout.lines.map(&:strip).grep(/\Ari-diagnostic:(?:match|mismatch|error):(?:valid|not_signed|not_trusted|hash_mismatch|unknown_error|other|error):(?:present|absent|unknown)\z/).last
          diagnostic_marker = marker if checked.exitcode == 0 && marker
        ensure
          begin
            if directory_created
              removed = shell.run(directory_command.call('remove'))
              cleanup = 'confirmed' if removed.exitcode == 0 && removed.stdout.lines.map(&:strip).include?('ri-directory:removed')
            end
          rescue StandardError
            cleanup = 'unknown'
          end
          puts(diagnostic_marker + ':' + cleanup)
        end
      else
        remote = nil
        begin
          if job['localExe']
            # The path is generated by this process; the server cannot supply a remote path.
            result = shell.run("Join-Path $env:TEMP 'remora-#{job.fetch('operationId')}.exe'")
            raise 'temp failed' unless result.exitcode == 0
            remote = result.stdout.strip
            raise 'invalid temp path' unless remote.match?(/\A[A-Za-z]:\\[^\r\n']+\.exe\z/)
            WinRM::FS::FileManager.new(connection).upload(job['localExe'], remote)
          end
          encoded = [job.fetch('script')].pack('m0')
          # Invoke script in this shell; no shell interpolation of host/credentials.
          script = "$s=[Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('#{encoded}')); & ([scriptblock]::Create($s)) -Mode '#{job.fetch('mode')}' -OperationId '#{job.fetch('operationId')}' -Installer '#{remote}' -InstallerSha256 '#{job.fetch('installerSha256')}'"
          result = shell.run(script)
          # Only protocol markers leave the process; never forward remote output/errors.
          marker = result.exitcode == 0 ? result.stdout.lines.map(&:strip).grep(/\Ari-result:[a-z_]+\z/).last : nil
          puts(marker || 'ri-result:outcome_unknown')
        ensure
          shell.run("Remove-Item -LiteralPath '#{remote}' -Force -ErrorAction SilentlyContinue") if remote
        end
      end
    end
  ensure
    FileUtils.rm_f(File.join(directory, 'ccache'))
  end
rescue StandardError
  # Exceptions can contain credentials, SOAP, target paths or Kerberos diagnostics.
  puts 'ri-result:outcome_unknown'
  exit 1
end
